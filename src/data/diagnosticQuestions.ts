export function getDiagnosticQuestionsForCycle(cycle: number = 1): Question[] {
  if (cycle <= 1) return DIAGNOSTIC_QUESTIONS;
  
  // For subsequent cycles, provide targeted variation or shuffled arrangement
  // keeping domain balance (5 questions per domain)
  return DIAGNOSTIC_QUESTIONS.map((q, idx) => {
    return {
      ...q,
      id: `diag-c${cycle}-${idx + 1}`,
    };
  });
}
